"""Build tests/evals/.dataset.json: end-to-end goldens with planted ground truth.

Nothing here is hand-written. Every golden is a plant generated by `rae.data.generator` with a cause planted at a
known segment and rate (or none, for controls), plus the complaint that a customer would send about it:
- the 3 demo stories on the seed-42 plant (dryer + sampling cut, worn mould + overdue gauge, no cause);
- the 14 benchmark plants (`rae.benchmark.CASES`), on two independent seed series each.

    python tests/evals/build_dataset.py
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT))

from rae.analytics import DEFECT_WORDS, seg_label  # noqa: E402
from rae.benchmark import CASES  # noqa: E402
from rae.data.cases import SEED_CASES  # noqa: E402

SEED_SERIES = (100, 300)  # 100 is the published benchmark's series; 300 is held out
STORIES = {
    "118": {"planted": {"press": "P4"}, "mechanism": "dryer", "escape": "sampling"},
    "124": {"planted": {"press": "P2", "cavity": "C3"}, "mechanism": "mould_wear", "escape": "gauge"},
    "121": {"planted": None, "mechanism": None, "escape": None},
}


def goldens() -> list[dict]:
    out = []
    for case in SEED_CASES:
        st = STORIES[case["case_id"]]
        out.append({
            "name": f"story-{case['case_id']}",
            "input": case["complaint"],
            "expected_output": seg_label(st["planted"]) if st["planted"] else "insufficient evidence",
            "additional_metadata": {"kind": "story", "case_id": case["case_id"], "defect": case["defect"],
                                    "start": case["date_code_start"], "end": case["date_code_end"], "seed": 42,
                                    "planted": st["planted"], "rate": None,
                                    "mechanism": st["mechanism"], "escape": st["escape"]},
        })
    for base in SEED_SERIES:
        for i, (cid, defect, filters, s, e, rate) in enumerate(CASES):
            words = DEFECT_WORDS.get(defect, defect)
            out.append({
                "name": f"{cid}-seed{base + i}",
                "input": (f"We found {words} on parts with date codes {s} to {e}. "
                          f"Please contain the stock and send an 8D report."),
                "expected_output": seg_label(filters) if filters else "insufficient evidence",
                "additional_metadata": {"kind": "benchmark", "case_id": cid, "defect": defect, "start": s, "end": e,
                                        "seed": base + i, "planted": filters, "rate": rate,
                                        "mechanism": None, "escape": None},
            })
    return out


if __name__ == "__main__":
    path = Path(__file__).resolve().parent / ".dataset.json"
    data = goldens()
    path.write_text(json.dumps(data, indent=1, ensure_ascii=False) + "\n", encoding="utf-8")
    print(f"wrote {len(data)} goldens to {path}")
